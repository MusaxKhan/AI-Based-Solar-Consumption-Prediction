// Reads PROJECT_URL and ANON_KEY from a .env file in the repo root and writes
// config.js (gitignored) so index.html has a default Supabase project baked
// in — new users land straight on login/signup instead of being asked to
// paste a Supabase URL and anon key themselves.
//
// No npm install needed — this is a plain Node script with a tiny hand-rolled
// .env parser, so there's nothing extra to install or keep updated.
//
// Usage:
//   1. Create a .env file in the repo root (same folder as index.html):
//        PROJECT_URL=https://xxxxx.supabase.co
//        ANON_KEY=eyJhbGciOi...
//   2. Run:  node scripts/build-config.js
//   3. Re-run it any time you change .env — config.js needs regenerating,
//      it isn't watched automatically.
//
// Deploying (Vercel/Netlify/etc.): set PROJECT_URL and ANON_KEY as
// environment variables in your host's dashboard (free on every major
// static host), and add `node scripts/build-config.js` as the build command
// so config.js gets generated fresh on every deploy — nothing to remember
// to run by hand in production.

const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const envPath = path.join(root, '.env');
const outPath = path.join(root, 'config.js');

function parseEnvFile(filePath){
  const out = {};
  if(!fs.existsSync(filePath)) return out;
  const text = fs.readFileSync(filePath, 'utf8');
  for(const rawLine of text.split('\n')){
    const line = rawLine.trim();
    if(!line || line.startsWith('#')) continue;
    const eq = line.indexOf('=');
    if(eq === -1) continue;
    const key = line.slice(0, eq).trim();
    let value = line.slice(eq + 1).trim();
    // strip matching surrounding quotes, if present
    if((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))){
      value = value.slice(1, -1);
    }
    out[key] = value;
  }
  return out;
}

// Environment variables (e.g. set in a hosting dashboard) win over .env,
// so the same script works for both local dev and CI/deploy builds.
const fileEnv = parseEnvFile(envPath);
const projectUrl = process.env.PROJECT_URL || fileEnv.PROJECT_URL;
const anonKey = process.env.ANON_KEY || fileEnv.ANON_KEY;

if(!projectUrl || !anonKey){
  console.error(
    'Missing PROJECT_URL and/or ANON_KEY.\n' +
    'Create a .env file in the repo root (see config.example.js for the shape) ' +
    'or set them as environment variables in your hosting dashboard.'
  );
  process.exit(1);
}

const contents =
`// GENERATED by scripts/build-config.js — do not edit by hand, do not commit.
// Regenerate with: node scripts/build-config.js
window.__SUPABASE_URL__ = ${JSON.stringify(projectUrl)};
window.__SUPABASE_ANON_KEY__ = ${JSON.stringify(anonKey)};
`;

fs.writeFileSync(outPath, contents);
console.log('Wrote ' + outPath);